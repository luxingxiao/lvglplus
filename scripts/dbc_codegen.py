#!/usr/bin/env python3
"""DBC -> cantools C codec + transport-neutral mapped-signal wrapper.

Generated code uses the cantools MIT notice emitted by cantools. This wrapper is Apache-2.0.
Unsupported extended multiplexing is rejected rather than silently decoding wrong branches.
"""
import argparse
import json
from pathlib import Path
import re
import cantools
from cantools.database.can import c_source

def snake(name):
    return re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)).lower()

def cstr(s):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in [34, 92] else '\\' + format(b, '03o') for b in s.encode()) + '"'

def generate(dbc, mappings, out):
    db = cantools.database.load_file(dbc, strict=True)
    names = {f'{m.name}.{s.name}' for m in db.messages for s in m.signals}
    unknown = set(mappings) - names
    if unknown:
        raise ValueError(f'Unknown DBC mappings: {sorted(unknown)}')
    for m in db.messages:
        if not re.fullmatch(r'[A-Za-z_]\w*', m.name) or any(not re.fullmatch(r'[A-Za-z_]\w*', s.name) for s in m.signals):
            raise ValueError('DBC message and signal names must be identifiers')
        muxes = [s for s in m.signals if s.is_multiplexer]
        if len(muxes) > 1 or any(s.is_multiplexer and s.multiplexer_signal for s in m.signals):
            raise ValueError(f'Extended/nested multiplexing not supported: {m.name}')
    out.mkdir(parents=True, exist_ok=True)
    header, source, _, _ = c_source.generate(db, 'database', 'database.h', 'database.c', 'database_fuzzer.c')
    # cantools embeds wall-clock generation dates. Remove only that line for deterministic artifacts.
    header = re.sub(r'\* @brief This header file was generated.*', '* @brief Generated by pinned cantools for LVGL Plus.', header)
    source = re.sub(r'\* @brief This source file was generated.*', '* @brief Generated by pinned cantools for LVGL Plus.', source)
    (out / 'database.h').write_text(header)
    (out / 'database.c').write_text(source)
    lines = ['/* SPDX-License-Identifier: Apache-2.0 */', '#include "lvglplus.h"', '#include "database.h"', '#include <math.h>',
             'int lvp_dbc_decode(const lvp_can_frame *f,lvp_emit_fn emit,void *user) {',
             '  if(lvp_can_validate(f)!=LVP_OK || !emit)return LVP_RANGE;']
    for m in sorted(db.messages, key=lambda msg: (msg.frame_id, msg.is_extended_frame)):
        mapped = [s for s in m.signals if f'{m.name}.{s.name}' in mappings]
        if not mapped:
            continue
        name = snake(m.name)
        lines += [f'  if(f->id=={m.frame_id}u && f->extended=={int(m.is_extended_frame)}) {{',
                  f'    struct database_{name}_t msg;',
                  f'    if(f->length!={m.length} || (f->length>8 && !f->fd))return LVP_RANGE;',
                  f'    if(database_{name}_unpack(&msg,f->data,f->length)<0)return LVP_ERROR;']
        for s in mapped:
            field = snake(s.name)
            prefix = f'database_{name}_{field}'
            guard = ''
            if s.multiplexer_signal:
                selector = snake(s.multiplexer_signal)
                guard = 'if(' + ' || '.join(f'msg.{selector}=={v}' for v in s.multiplexer_ids) + ')'
            lines.append(f'    {guard}{{if(!{prefix}_is_in_range(msg.{field}) || !isfinite({prefix}_decode(msg.{field})))return LVP_RANGE;}}')
        for s in mapped:
            field = snake(s.name)
            guard = ''
            if s.multiplexer_signal:
                selector = snake(s.multiplexer_signal)
                guard = 'if(' + ' || '.join(f'msg.{selector}=={v}' for v in s.multiplexer_ids) + ')'
            lines.append(f'    {guard}emit({cstr(mappings[f"{m.name}.{s.name}"])},database_{name}_{field}_decode(msg.{field}),f->timestamp_ms,user);')
        lines += ['    return LVP_OK;', '  }']
    lines += ['  return LVP_NOT_FOUND;', '}', '']
    (out / 'lvp_dbc.c').write_text('\n'.join(lines))
    (out / 'dbc-manifest.json').write_text(json.dumps({'cantools': cantools.__version__, 'messages': len(db.messages), 'mappings': mappings}, indent=2) + '\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('dbc', type=Path)
    parser.add_argument('sources', type=Path)
    parser.add_argument('out', type=Path)
    a = parser.parse_args()
    generate(a.dbc, json.loads(a.sources.read_text()).get('mappings', {}), a.out)
